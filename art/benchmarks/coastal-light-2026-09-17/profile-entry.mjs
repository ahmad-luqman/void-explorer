import { chromium } from '../../../game/node_modules/playwright/index.mjs';
import { resolve } from 'node:path';
const output = resolve(process.env.PROFILE_OUTPUT || 'coast-webgpu');
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({headless:true,args:['--use-angle=metal']});
const page=await browser.newPage({viewport:{width:1440,height:960}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{localStorage.setItem('void-renderer','auto');window.frameDiagnostic={frames:[],tasks:[],states:[]};new PerformanceObserver(list=>{for(const e of list.getEntries())window.frameDiagnostic.tasks.push({start:e.startTime,duration:e.duration});}).observe({type:'longtask',buffered:true});let last;function tick(t){if(last)window.frameDiagnostic.frames.push([t,t-last]);last=t;requestAnimationFrame(tick);}requestAnimationFrame(tick);setInterval(()=>{const s=window.__VOID_EXPLORER__?.state();if(s)window.frameDiagnostic.states.push({time:performance.now(),contactReady:s.contactReady,streaming:s.streaming,contactStats:s.contactStats});},500);});
await page.goto(process.env.PLAYWRIGHT_BASE_URL || 'http://127.0.0.1:4173');
await page.getByRole('button',{name:'START EXPEDITION'}).waitFor();
await page.waitForFunction(()=>!document.querySelector('.start-button')?.disabled);
await page.getByRole('button',{name:'START EXPEDITION'}).click({timeout:45000});
await page.waitForTimeout(9500);
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Return to title'}).click();
const cdp=await page.context().newCDPSession(page);
await cdp.send('Profiler.enable');await cdp.send('Profiler.setSamplingInterval',{interval:1000});await cdp.send('Profiler.start');
const start=await page.evaluate(()=>performance.now());
await page.getByRole('button',{name:'Explore Lumen Coast'}).click();
await page.waitForTimeout(20000);
const end=await page.evaluate(()=>performance.now());
const {profile}=await cdp.send('Profiler.stop');
const diagnostic=await page.evaluate(()=>window.frameDiagnostic);
await writeFile(output + '.cpuprofile',JSON.stringify(profile));
await writeFile(output + '-diagnostic.json',JSON.stringify({start,end,errors,...diagnostic},null,2));
console.log(JSON.stringify({start,end,errors,tasks:diagnostic.tasks.filter(x=>x.start>=start),slowFrames:diagnostic.frames.filter(x=>x[0]>=start&&x[1]>50)}));
await browser.close();
